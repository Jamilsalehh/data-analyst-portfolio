    q.to_csv(OUT / "calls_queue_hourly.csv", index=False)
    a.to_csv(OUT / "calls_agent_daily.csv", index=False)
    for c in ("created_at", "first_reply_at", "solved_at"):
        tk[c] = pd.to_datetime(tk[c]).dt.strftime("%Y-%m-%d %H:%M:%S")
    tk.to_csv(OUT / "tickets.csv", index=False)
    print({"agents": len(ag), "calls_queue_hourly": len(q), "calls_agent_daily": len(a), "tickets": len(tk)})
